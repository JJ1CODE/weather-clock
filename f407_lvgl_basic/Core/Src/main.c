static void touch_read(lv_indev_t *indev, lv_indev_data_t *data)
{

	touchStatus = HAL_I2C_Mem_Read(
	    &hi2c1, 0x38U << 1, 0x02,
	    I2C_MEMADD_SIZE_8BIT, touch, 5, 50);

	data->state = LV_INDEV_STATE_RELEASED;
	data->point.x = touchX;
	data->point.y = touchY;

	if(touchStatus == HAL_OK && (touch[0] & 0x0F) ==1U)
	{
		uint16_t x = ((uint16_t)(touch[1]&0x0F) << 8) | touch[2];
		uint16_t y = ((uint16_t)(touch[3]&0x0F) << 8) | touch[4];

		if(x<240 && y<320)
		{
			touchX = x;
			touchY = y;
			data->point.x = x;
			data->point.y = y;
			data->state = LV_INDEV_STATE_PRESSED;

		}
	}


}

